"""The design tokens: reading ``tokens/tokens.json`` and writing what is made from it.

The file is DTCG-shaped (a token is an object with ``$value`` and ``$type``)
with two things of its own: a color's ``$value`` is a CSS color string (a hex
where it is opaque), and a token may be composed from two others with
``$compose`` (one color at an alpha over another), so a derived color is
computed here and never stored.
"""
from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Any

from . import BRAND_ROOT

TOKENS_JSON = Path("tokens/tokens.json")
FLAT_JSON = Path("tokens/dist/tokens.flat.json")
TOKENS_CSS = Path("tokens/dist/kleidos-tokens.css")

HEX = re.compile(r"#[0-9a-fA-F]{6}")
ALIAS = re.compile(r"\{([A-Za-z0-9_.-]+)\}")

#: The groups whose opaque colors go into the flat file, in file order.
FLAT_GROUPS = ("brand", "social", "web.dark", "web.light", "device.dark", "device.eink", "schematic")

#: The nine type roles of the site and the seven parts each one declares.
TYPE_PARTS = (("size", ""), ("lh", "-lh"), ("track", "-track"), ("face", "-face"),
              ("weight", "-weight"), ("width", "-width"), ("fvs", "-fvs"))


def load(root: Path = BRAND_ROOT) -> dict[str, Any]:
    """Return ``tokens/tokens.json`` of the repository at *root*."""
    return json.loads((root / TOKENS_JSON).read_text(encoding="utf-8"))


def leaves(tree: dict[str, Any], prefix: str = "") -> dict[str, dict[str, Any]]:
    """Return every token of *tree* by its dotted name."""
    found: dict[str, dict[str, Any]] = {}
    for key, value in tree.items():
        if key.startswith("$") or not isinstance(value, dict):
            continue
        name = f"{prefix}{key}"
        if "$value" in value or "$compose" in value:
            found[name] = value
        else:
            found.update(leaves(value, f"{name}."))
    return found


def hex_rgb(color: str) -> tuple[int, int, int]:
    """Return the red, green and blue of a ``#rrggbb`` color."""
    if not HEX.fullmatch(color):
        raise ValueError(f"not a #rrggbb color: {color!r}")
    return int(color[1:3], 16), int(color[3:5], 16), int(color[5:7], 16)


def rgb_hex(rgb: tuple[int, int, int]) -> str:
    """Return ``#rrggbb``, lower case."""
    return "#{:02x}{:02x}{:02x}".format(*rgb)


def over(color: str, ground: str, alpha: float) -> str:
    """Return the opaque color of *color* at *alpha* over *ground*, as sRGB bytes are blended."""
    top, under = hex_rgb(color), hex_rgb(ground)
    return rgb_hex(tuple(round(t * alpha + u * (1 - alpha)) for t, u in zip(top, under, strict=True)))  # type: ignore[arg-type]


def resolve(tokens: dict[str, Any]) -> dict[str, Any]:
    """Return every token's value by its dotted name, aliases followed and compositions computed.

    A color comes back as lower-case ``#rrggbb`` where it is opaque and as
    written otherwise; anything else comes back as written.
    """
    found = leaves(tokens)
    done: dict[str, Any] = {}

    def value_of(name: str, trail: tuple[str, ...] = ()) -> Any:
        if name in done:
            return done[name]
        if name not in found:
            raise KeyError(f"tokens.json has no token {name!r}")
        if name in trail:
            raise ValueError(f"tokens.json: {' -> '.join((*trail, name))} is a loop")
        token = found[name]
        if "$compose" in token:
            parts = token["$compose"]
            color = value_of(ALIAS.fullmatch(parts["color"]).group(1), (*trail, name))  # type: ignore[union-attr]
            ground = value_of(ALIAS.fullmatch(parts["over"]).group(1), (*trail, name))  # type: ignore[union-attr]
            value: Any = over(color, ground, float(parts["alpha"]))
        else:
            value = token["$value"]
            alias = ALIAS.fullmatch(value) if isinstance(value, str) else None
            if alias:
                value = value_of(alias.group(1), (*trail, name))
            elif isinstance(value, str) and HEX.fullmatch(value):
                value = value.lower()
        done[name] = value
        return value

    for name in found:
        value_of(name)
    return done


def flat(tokens: dict[str, Any]) -> dict[str, str]:
    """Return the opaque colors of :data:`FLAT_GROUPS`, name to ``#rrggbb``."""
    values = resolve(tokens)
    return {
        name: value
        for name, value in values.items()
        if isinstance(value, str) and HEX.fullmatch(value) and any(name.startswith(f"{group}.") for group in FLAT_GROUPS)
    }


def flat_json(tokens: dict[str, Any]) -> str:
    """Return the text of ``tokens/dist/tokens.flat.json``."""
    body = {"$comment": "Generated by tools/build.py from tokens/tokens.json. Do not edit.", **flat(tokens)}
    return json.dumps(body, indent=2, ensure_ascii=False) + "\n"


def palette(tokens: dict[str, Any]) -> frozenset[str]:
    """Return every opaque color the tokens define: what an image may be painted with."""
    return frozenset(flat(tokens).values())


# --- Contrast ----------------------------------------------------------------------------


def luminance(color: str) -> float:
    """Return the WCAG 2 relative luminance of a ``#rrggbb`` color."""
    def channel(byte: int) -> float:
        share = byte / 255
        return share / 12.92 if share <= 0.04045 else ((share + 0.055) / 1.055) ** 2.4

    red, green, blue = (channel(byte) for byte in hex_rgb(color))
    return 0.2126 * red + 0.7152 * green + 0.0722 * blue


def contrast(first: str, second: str) -> float:
    """Return the WCAG 2 contrast ratio of two ``#rrggbb`` colors."""
    lighter, darker = sorted((luminance(first), luminance(second)), reverse=True)
    return (lighter + 0.05) / (darker + 0.05)


def rgb565(color: str) -> str:
    """Return the 16-bit value a panel stores for *color*, as the firmware computes it."""
    red, green, blue = hex_rgb(color)
    return f"0x{((red & 0xF8) << 8) | ((green & 0xFC) << 3) | (blue >> 3):04X}"


def cmyk(color: str) -> tuple[int, int, int, int]:
    """Return *color* as cyan, magenta, yellow and black percentages, converted by arithmetic.

    No press profile is applied, so the result is where a proof starts, not a
    promise of what a press prints.
    """
    red, green, blue = (byte / 255 for byte in hex_rgb(color))
    black = 1 - max(red, green, blue)
    if black == 1:
        return 0, 0, 0, 100
    return tuple(round(100 * (1 - part - black) / (1 - black)) for part in (red, green, blue)) + (round(100 * black),)  # type: ignore[return-value]


# --- The stylesheet ----------------------------------------------------------------------


def _declarations(group: dict[str, Any], values: dict[str, Any], prefix: str, css_prefix: str = "") -> list[str]:
    return [f"  --{css_prefix}{name[len(prefix) + 1:].replace('.', '-')}: {values[name]};" for name in leaves(group, f"{prefix}.")]


def css(tokens: dict[str, Any]) -> str:
    """Return the text of ``tokens/dist/kleidos-tokens.css``.

    The custom properties carry the site's own names (``--signal``,
    ``--ink-2``, ``--t-hero``), so the site's token blocks can be compared
    with this file, or replaced by it, line for line.
    """
    values = resolve(tokens)
    web = tokens["web"]
    dark = _declarations(web["dark"], values, "web.dark")
    for role, parts in web["type"]["roles"].items():
        for part, suffix in TYPE_PARTS:
            dark.append(f"  --t-{role}{suffix}: {parts[part]['$value']};")
    for name in ("faces", "radius", "motion"):
        dark += _declarations(web[name], values, f"web.{name}")
    light = _declarations(web["light"], values, "web.light")
    device = _declarations(tokens["device"]["dark"], values, "device.dark", "device-")
    eink = _declarations(tokens["device"]["eink"], values, "device.eink", "eink-")
    brand = [f"  --brand-{key}: {values[f'brand.{key}']};" for key in ("signal", "select")]
    lines = [
        # REUSE-IgnoreStart
        "/* SPDX-License-Identifier: MIT */",
        # REUSE-IgnoreEnd
        "/* Generated by tools/build.py from tokens/tokens.json. Do not edit. */",
        "",
        "/* The web palette, dark by default, under the names the site's sheet uses. */",
        ":root {",
        *brand,
        *dark,
        "  color-scheme: dark;",
        "}",
        "",
        "/* The light theme, for a reader whose system asks for it and has not chosen dark. */",
        "@media (prefers-color-scheme: light) {",
        '  :root:not([data-theme="dark"]) {',
        *(f"  {line}" for line in light),
        "    color-scheme: light;",
        "  }",
        "}",
        "",
        "/* The same theme, for a reader who chose it. */",
        ':root[data-theme="light"] {',
        *light,
        "  color-scheme: light;",
        "}",
        "",
        "/* The device's own palette: what its panels draw, for a mockup of a screen. */",
        '[data-kl="device"] {',
        *device,
        *eink,
        "}",
        "",
    ]
    return "\n".join(lines)
